import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('..',import.meta.url));
const esbuild=await import(process.env.FONTBOX_ESBUILD_PATH||'esbuild');
const {version}=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
const css=await readFile(path.join(root,'frontend/editor.css'),'utf8');
await writeFile(path.join(root,'frontend/styles.js'),`// Generated by scripts/build.mjs from editor.css.\nexport const EDITOR_STYLES = ${JSON.stringify(css)};\n`);
const directory=path.join(root,'web',`fontbox-${version}`);await mkdir(directory,{recursive:true});
await esbuild.build({entryPoints:[path.join(root,'frontend/comfy.js')],outfile:path.join(directory,`fontbox-${version}.js`),
    bundle:true,format:'esm',platform:'browser',target:'es2019',
    external:['../../scripts/app.js','../../scripts/api.js'],banner:{js:`// FontBox ${version}: self-contained frontend and embedded styles.`}});
console.log(`Built web/fontbox-${version}/fontbox-${version}.js`);
